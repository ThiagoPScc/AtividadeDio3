df = pd.read_csv(url)
df.head()

print("Dimensões:", df.shape)
display(df.info())

display(df.describe().T)
print("Valores ausentes:", int(df.isna().sum().sum()))
print("Linhas duplicadas:", int(df.duplicated().sum()))
print("\nDistribuição da classe:")
display(df["Class"].value_counts().to_frame("quantidade"))
class_share = df["Class"].value_counts(normalize=True).sort_index() * 100
display(class_share.to_frame("percentual"))

ax = sns.countplot(data=df, x="Class")
